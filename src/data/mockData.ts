export const FORMAT_IDR = (num: number): string => {
  return new Intl.NumberFormat('id-ID', {
    style: 'currency',
    currency: 'IDR',
    maximumFractionDigits: 0,
  }).format(num);
};

export const FORMAT_IDR_SHORT = (num: number): string => {
  if (num >= 1000000000) {
    return `Rp ${(num / 1000000000).toFixed(2)} M`;
  }
  if (num >= 1000000) {
    return `Rp ${(num / 1000000).toFixed(1)} Jt`;
  }
  if (num >= 1000) {
    return `Rp ${(num / 1000).toFixed(0)} Rb`;
  }
  return `Rp ${num}`;
};

export const FORMAT_PERCENT = (num: number): string => {
  return `${num >= 0 ? '+' : ''}${num.toFixed(1)}%`;
};
